#ifndef SINTENCE_ANALYSIS_INDEX_BUILDER_H
#define SINTENCE_ANALYSIS_INDEX_BUILDER_H

#include "champion_index.h"
#include "match_source.h"  // интерфейс источника
#include <utility>
// analysis/index_builder — сборка индекса чемпионов из произвольного источника.
//
// Работает только через интерфейс MatchSource и не знает, откуда пришли
// данные: файлы, сеть или фикстуры. Источник спрашивается ровно один раз —
// для Match-V5 это сетевой запрос, а не бесплатная операция.
// Недоступный источник даёт пустой индекс, а не исключение.

namespace sintence {

// Собирает индекс отчётов по чемпионам из любого источника матчей.
//
// Контракт:
//   - недоступный источник (IsAvailable() == false) даёт пустой индекс;
//   - на каждое имя чемпиона — ровно один отчёт со всеми его строками;
//   - порядок чемпионов в индексе — порядок первого появления в записях;
//   - записи с пустым champion_name отбрасываются целиком: отчёт без имени
//     невозможно найти через Find, и в таблице ему нечего показать;
//   - валидность самих строк матча не проверяется здесь — это работа
//     ChampionReport::Add. Чемпион, у которого все строки
//     оказались негодными, остаётся в индексе с нулём игр: он в выгрузке
//     был, и честнее показать его с нулём, чем молча потерять.
ChampionIndex BuildChampionIndex(const MatchSource& source);

}  // namespace sintence

#endif  // SINTENCE_ANALYSIS_INDEX_BUILDER_H
