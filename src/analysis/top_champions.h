#ifndef COURSE_TOPIC05_TOP_CHAMPIONS_H
#define COURSE_TOPIC05_TOP_CHAMPIONS_H

#include <cstddef>
#include <map>
#include <string>
#include <vector>

// ============================================================================
// Задача 5.1 — топ чемпионов по числу игр
//
// Критерии приёмки — кратко; подробности, сигнатуры и поток данных
// в TODO рядом с телом функции в top_champions.cpp:
//   1. Сортировка — одним вызовом алгоритма STL, без своего цикла с обменами.
//   2. Порядок при равном числе игр задан компаратором явно, а не случайно.
//   3. limit больше размера таблицы — не ошибка и не UB.
//   4. Заглушек и TODO в файле не осталось.
//
// Одна идея этой задачи: алгоритм плюс лямбда-компаратор вместо ручного цикла,
// и тай-брейк как часть контракта, а не как побочный эффект данных.
//
// Callback к задаче 4.1: на входе ровно то, что возвращает CountGamesByChampion.
// Тест это и делает — прогоняет записи через твою функцию из темы 4 и передаёт
// результат сюда.
//
// Зачем это анализатору: «топ-5 чемпионов» — первая строка любого профиля.
// В теме 18 эта же функция встанет за колонкой таблицы, которую сортируют
// кликом по заголовку.
// ============================================================================

namespace course {

// Строка таблицы «чемпион — сколько игр».
//
// Структура, а не класс: голые поля, никаких инвариантов
// («Чистый код», глава 6). Нужна потому, что std::map отдаёт пары
// std::pair<const std::string, int>, а наружу удобнее отдавать
// именованные поля, а не .first / .second.
struct ChampionGames {
    std::string champion_name;
    int games = 0;
};

// Топ чемпионов по числу игр.
//
// Контракт:
//   - порядок: по УБЫВАНИЮ числа игр;
//   - при равном числе игр — по ВОЗРАСТАНИЮ имени ("Ahri" раньше "Zed");
//     это часть контракта, а не то, как получилось: тест проверяет;
//   - limit — сколько строк вернуть максимум. limit == 0 даёт пустой вектор,
//     limit больше размера таблицы — всю таблицу, без выхода за границы;
//   - пустая таблица даёт пустой вектор.
//
// Чемпионы с нулём игр в таблицу не попадают по построению (CountGamesByChampion
// создаёт ключ только на непустой записи), поэтому отдельно их отбрасывать
// здесь не нужно.
std::vector<ChampionGames> TopChampionsByGames(const std::map<std::string, int>& games,
                                               std::size_t limit);

}  // namespace course

#endif  // COURSE_TOPIC05_TOP_CHAMPIONS_H
