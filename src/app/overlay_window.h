#ifndef SINTENCE_APP_OVERLAY_WINDOW_H
#define SINTENCE_APP_OVERLAY_WINDOW_H

#include <functional>
#include <string>
#include <string_view>

// app/overlay_window — окно поверх игры с WebView2 внутри.
//
// Окно непрозрачное и прямоугольное, панель занимает его целиком.
// Прозрачность по цветовому ключу здесь была и убрана: у layered-окна
// Windows считает hit-test по видимой области слоя, поэтому клик по
// пикселю цвета ключа проваливается в игру, и обойти это из оконной
// процедуры нельзя. Выбор стоял между «красивые скруглённые края» и
// «по панели можно кликать», и второе важнее.
//
// Настоящая прозрачность со скруглениями возможна через DirectComposition
// с попиксельной альфой, но мышь сквозь альфу проваливается точно так же.
//
// Поверх эксклюзивного полноэкранного режима не отрисуется ничего — это
// ограничение Windows. Нужен режим Borderless; современный Windows
// подменяет «полный экран» на borderless сам почти всегда.

namespace sintence {

struct OverlayOptions {
    std::wstring url;            // что показывать: http://127.0.0.1:8777/
    std::wstring title = L"Sintence";

    // Вдвое больше исходных 1120x640: в карточку добавились предметы,
    // ранг, пул чемпионов и строка меты, и в прежний размер они влезали
    // только обрезанными. Размер обрезается по экрану при показе
    // (90% от него), поэтому на 1920x1080 панель не уезжает за край.
    int width = 2240;
    int height = 1280;

    // Окно статистики (app/profile_window). Пусто — только оверлей.
    std::wstring profile_url;

    // Порт сервера данных: по нему второй запуск находит своё окно
    // (AcquireSingleInstance).
    int port = 8777;

    // Каталог данных WebView2 (кеш, localStorage). Пусто — рядом с exe.
    std::wstring user_data_dir;

    // Есть ли что показать на панели: идёт выбор чемпиона, экран загрузки
    // или матч. Зовётся раз в секунду из фонового потока. Пока false,
    // PgDn панель не открывает и не перехватывается. Пусто — панель
    // открывается всегда, как раньше.
    std::function<bool()> has_content;
};

// Создаёт окно СКРЫТЫМ, поднимает WebView2 и крутит цикл сообщений.
// Возвращает код возврата приложения.
//
// Управление: PgDn показывает и прячет панель.
//
// Дизайн окна живёт в интерфейсе: страница присылает через
// chrome.webview.postMessage размер, место на экране, фон и клавишу
// (overlay/config) и может попросить спрятать панель (overlay/hide).
// OverlayOptions — только значения до первого сообщения.
//
// Положение задаёт интерфейс (по центру или у верхнего края, со сдвигом),
// мышью панель не двигается. Открытая панель забирает фокус — клавиатура
// и мышь принадлежат ей, а не игре.
//
// PgDn ловится низкоуровневым хуком клавиатуры, а не RegisterHotKey:
// игры регистрируют Raw Input с флагом RIDEV_NOHOTKEYS, который отключает
// системные горячие клавиши, пока игра активна.
//
// Права администратора нужны, чтобы окно поднималось поверх игры с анти-читом
// (app/sintence.manifest и /MANIFESTUAC в src/CMakeLists.txt).
//
// Консоли у приложения нет, оно живёт в трее (app/tray_icon): крестик окна
// статистики прячет его, PgDn работает дальше. Выход — «Выход» в меню
// значка; снятая в диспетчере задач программа просто исчезает.
int RunOverlay(const OverlayOptions& options);

// Одна копия на порт. false — копия уже запущена: ей отправлена просьба
// показать окно статистики, этой копии надо завершиться.
bool AcquireSingleInstance(int port);

// Ошибка, из-за которой приложение не может работать: в журнал и окном
// сообщения: консоли, где её раньше было видно, у приложения нет.
void ShowErrorBox(std::string_view text);

}  // namespace sintence

#endif  // SINTENCE_APP_OVERLAY_WINDOW_H
