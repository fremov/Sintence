#ifndef SINTENCE_APP_OVERLAY_WINDOW_H
#define SINTENCE_APP_OVERLAY_WINDOW_H

#include <string>

// app/overlay_window — прозрачное окно поверх игры с WebView2 внутри.
//
// Как устроена прозрачность: окно layered, цветовой ключ — пурпурный
// (#FF00FF). Фон WebView2 прозрачный, под ним пурпурный фон окна, который
// Windows вырезает. Ограничение способа: сглаженные края (скругления, тени
// по внешнему краю) в ключ не попадают точно и остаются видимой каймой,
// поэтому внешний край панели в CSS сделан прямым.
//
// Альтернатива — DirectComposition с попиксельной альфой: даёт настоящие
// тени и скругления ценой заметного объёма работы с COM.
//
// Поверх эксклюзивного полноэкранного режима не отрисуется ничего — это
// ограничение Windows. Нужен режим Borderless; современный Windows
// подменяет «полный экран» на borderless сам почти всегда.

namespace sintence {

struct OverlayOptions {
    std::wstring url;            // что показывать: http://127.0.0.1:8777/
    std::wstring title = L"Sintence";
    // Размер подобран под табло из двух колонок по пять карточек:
    // всё помещается без прокрутки, а больше десяти игроков в матче не бывает.
    int width = 1120;
    int height = 640;
};

// Создаёт окно СКРЫТЫМ, поднимает WebView2 и крутит цикл сообщений.
// Возвращает код возврата приложения.
//
// Управление: PgDn показывает и прячет панель. Всё.
//
// Панель всегда появляется по центру экрана: положение не запоминается
// и мышью не двигается. Открытая панель забирает фокус — клавиатура и мышь
// принадлежат ей, а не игре.
//
// PgDn ловится низкоуровневым хуком клавиатуры, а не RegisterHotKey:
// игры регистрируют Raw Input с флагом RIDEV_NOHOTKEYS, который отключает
// системные горячие клавиши, пока игра активна.
//
// Права администратора нужны, чтобы окно поднималось поверх игры с анти-читом
// (app/sintence.manifest и /MANIFESTUAC в src/CMakeLists.txt). Выход из
// программы — Ctrl+C в консоли.
int RunOverlay(const OverlayOptions& options);

}  // namespace sintence

#endif  // SINTENCE_APP_OVERLAY_WINDOW_H
