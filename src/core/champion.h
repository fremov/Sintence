#ifndef COURSE_TOPIC01_CHAMPION_H
#define COURSE_TOPIC01_CHAMPION_H

#include <string>

// ============================================================================
// Задача 1.1 — Champion
//
// Критерии приёмки (что значит «готово» сверх зелёных тестов):
//   1. Все поля private. Снаружи класс виден только через методы.
//   2. Каждый метод, который не меняет объект, объявлен const — и в .h, и в .cpp.
//   3. Инвариант держит конструктор: после его работы Name() и Role() никогда
//      не пустые, а Role() всегда в верхнем регистре. Проверять это в геттерах
//      не нужно — если инвариант приходится перепроверять, значит он не инвариант.
//   4. Тело конструктора пустое: вся инициализация в списке инициализации.
//   5. Заглушка kStub из champion.cpp удалена.
//
// Одна идея этой задачи: класс — это приватные данные плюс публичное поведение,
// и за корректность данных отвечает сам класс, а не тот, кто им пользуется.
// ============================================================================

namespace course {

class Champion {
public:
    // Создаёт чемпиона.
    //   name — как в поле participant.championName из данных Riot: "Ahri", "LeeSin".
    //   role — как в participant.teamPosition: "TOP", "JUNGLE", "MIDDLE",
    //          "BOTTOM", "UTILITY".
    //
    // Должен принять "middle", "Middle" и "MIDDLE" как одно и то же.
    // Должен отвергнуть пустые строки: пустое имя превращается в "Unknown",
    // пустая роль — в "UNKNOWN". В реальных матчах teamPosition приходит пустым,
    // когда игрок ушёл с линии на ранней стадии, и падать из-за этого нельзя.
    Champion(std::string name, std::string role);

    // Имя чемпиона как есть. Регистр не трогаем: "Ahri" — имя собственное,
    // и в отчёте оно должно выглядеть человечески.
    const std::string& Name() const;

    // Роль в верхнем регистре. Никогда не пустая.
    const std::string& Role() const;

    // Строка для отчёта: "Ahri (MIDDLE)".
    std::string DisplayName() const;

    // true, если роль совпадает с переданной без учёта регистра.
    // Нужен для фильтра «покажи только мид» в теме 5.
    // Пустой аргумент — не роль: должен вернуть false.
    bool HasRole(const std::string& role) const;

private:
    std::string name_;
    std::string role_;
};

}  // namespace course

#endif  // COURSE_TOPIC01_CHAMPION_H
