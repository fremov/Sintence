// ============================================================================
// Задача 2.3 — ChampionIndex: правило нуля
//
// Критерии приёмки (что значит «готово» сверх зелёных тестов):
//   1. В этом классе не объявлено и не определено ни одной из шести
//      специальных функций-членов: ни деструктора, ни копирования,
//      ни перемещения, ни конструктора по умолчанию. Ни в .h, ни в .cpp.
//   2. При этом индекс корректно копируется, перемещается и разрушается —
//      тесты это проверяют. Объясни себе, почему, прежде чем идти дальше.
//   3. AddReport принимает отчёт по значению и перемещает его в вектор,
//      а не копирует.
//   4. Find не создаёт копию отчёта: возвращает указатель на хранимый,
//      и const-корректность соблюдена.
//   5. Заглушек и TODO в файле не осталось.
//
// Одна идея этой задачи: если все поля управляют собой сами, правильная
// реализация пяти специальных функций — это ни одной написанной строки.
// Задачи 2.1 и 2.2 показали, во что обходится обратное.
//
// Callback к теме 1: внутри лежат ChampionReport'ы, собранные тобой неделю
// назад, вместе со всеми их метриками. Это первая точка, где куски анализатора
// начинают складываться друг с другом.
// ============================================================================

namespace course {

// Все отчёты по чемпионам в одном месте: то, что анализатор показывает
// на главном экране. Поиск линейный — std::map появится в теме 4,
// и там же станет видно, зачем он тут нужен.
class ChampionIndex {
public:
    // Добавляет отчёт в индекс.
    //
    // Принимает по значению сознательно: вызывающий сам решает, отдать копию
    // (index.AddReport(report)) или временный объект без копирования
    // (index.AddReport(std::move(report))). Внутри отчёт перемещается в вектор.
    //
    // Если отчёт по этому чемпиону уже есть — он заменяется целиком.
    // Иначе Find стал бы неоднозначным: два отчёта на одно имя.
    void AddReport(ChampionReport report);

    // Отчёт по имени чемпиона или nullptr, если такого нет.
    // Имя сравнивается точно, как оно пришло: нормализацией занимается Champion
    // из темы 1, а не индекс.
    const ChampionReport* Find(const std::string& champion_name) const;

    int Size() const;
    bool Empty() const;

    // Имена всех чемпионов в порядке добавления.
    std::vector<std::string> ChampionNames() const;

private:
    std::vector<ChampionReport> reports_;
};

}  // namespace course

#endif  // COURSE_TOPIC02_CHAMPION_INDEX_H
