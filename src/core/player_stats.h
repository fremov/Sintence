#ifndef COURSE_TOPIC01_PLAYER_STATS_H
#define COURSE_TOPIC01_PLAYER_STATS_H

#include <string>

// ============================================================================
// Задача 1.2 — PlayerStats
//
// Критерии приёмки (что значит «готово» сверх зелёных тестов):
//   1. Все поля private и проинициализированы там, где объявлены (int x = 0).
//   2. Единственный метод, который меняет объект, — AddMatch. Все остальные const.
//   3. Инвариант: счётчики никогда не отрицательные, Wins() <= Games(),
//      Losses() + Wins() == Games(). Держится сам собой, без проверок в геттерах.
//   4. Испорченная строка матча не учитывается вообще — ни в одном счётчике.
//      Частично учтённый матч хуже, чем пропущенный: он тихо портит статистику.
//   5. Заглушек и TODO в файле не осталось.
//
// Одна идея этой задачи: объект хранит изменяемое состояние, и менять его можно
// ровно одним способом — через метод, который отвечает за корректность.
// ============================================================================

namespace course {

class PlayerStats {
public:
    // champion_name — имя чемпиона, по которому копится статистика.
    // explicit, чтобы PlayerStats не создавался случайно из строки.
    explicit PlayerStats(std::string champion_name);

    // Добавляет результат одного матча.
    //
    // Отрицательные kills / deaths / assists — это испорченные данные
    // (в JSON бывает null, который парсер превратит в -1). Такой матч
    // должен быть отброшен целиком: Games() не растёт, счётчики не меняются.
    //
    // Нули — нормальные данные: 0/0/0 бывает при ремейке на четвёртой минуте.
    void AddMatch(int kills, int deaths, int assists, bool win);

    const std::string& ChampionName() const;

    // Сколько матчей учтено.
    int Games() const;

    // Побед и поражений. Losses() не хранится отдельным полем —
    // хранить то, что выводится из уже имеющегося, значит завести
    // второй источник правды и рано или поздно их рассинхронизировать.
    int Wins() const;
    int Losses() const;

    // Суммы по всем учтённым матчам.
    int TotalKills() const;
    int TotalDeaths() const;
    int TotalAssists() const;

private:
    std::string champion_name_;
    int games_ = 0;
    int wins_ = 0;
    int total_kills_ = 0;
    int total_deaths_ = 0;
    int total_assists_ = 0;
};

}  // namespace course

#endif  // COURSE_TOPIC01_PLAYER_STATS_H
