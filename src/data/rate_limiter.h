#ifndef SINTENCE_DATA_RATE_LIMITER_H
#define SINTENCE_DATA_RATE_LIMITER_H

#include <chrono>
#include <deque>
#include <vector>

// data/rate_limiter — счётчик запросов по скользящим окнам.
//
// Зачем он нужен именно здесь: ключ Riot ограничен 20 запросами в секунду
// И 100 запросами за 2 минуты одновременно. Лобби из десяти игроков — это
// 30 запросов, в секундное окно они влезают, а вот две игры подряд без
// ограничителя упрутся в двухминутное. Ответ на превышение — 429 и
// временная блокировка ключа, поэтому считать надо ДО отправки, а не
// разгребать последствия после.
//
// Почему окно скользящее, а не «сбрасываем счётчик раз в минуту»:
// Riot считает именно так. Фиксированный интервал позволяет отправить
// 100 запросов в конце одного окна и 100 в начале следующего — двести
// запросов за пару секунд, и ключ блокируется, хотя счётчик «не превышен».
//
// Часы передаются снаружи, а не берутся внутри. Это единственное, что
// делает класс тестируемым: тест на двухминутное окно, который честно
// ждёт две минуты, никто никогда не запустит.
//
// КРИТЕРИИ ГОТОВНОСТИ (задача 2 из трёх):
//   1. Все тесты test_rate_limiter.cpp зелёные.
//   2. Ни одного вызова Clock::now() внутри класса.
//   3. Ни одного sleep внутри класса: он считает, ждёт вызывающий.
//   4. Память не течёт: записи старше самого длинного окна выбрасываются,
//      а не копятся вечно.

namespace sintence {

class RateLimiter {
public:
    using Clock = std::chrono::steady_clock;
    using TimePoint = Clock::time_point;

    // Одно ограничение: не больше limit запросов за period.
    struct Window {
        int limit = 0;
        std::chrono::milliseconds period{0};
    };

    // Окна проверяются все сразу: разрешено то, что разрешено каждым.
    explicit RateLimiter(std::vector<Window> windows);

    // Лимиты personal-ключа: 20 запросов в секунду и 100 за 2 минуты.
    // Именованный конструктор вместо магических чисел по всему коду.
    static RateLimiter RiotPersonalKey();

    // Сколько ждать, прежде чем отправлять следующий запрос.
    //
    // Ноль — можно отправлять прямо сейчас. Иначе — сколько осталось
    // до момента, когда самая старая запись покинет заполненное окно.
    // Если окон заполнено несколько, ответ — максимум по ним.
    //
    // Метод const и ничего не меняет: спросить можно сколько угодно раз,
    // это не «занять слот».
    std::chrono::milliseconds DelayUntilAllowed(TimePoint now) const;

    // Отметить ОТПРАВЛЕННЫЙ запрос. Зовётся после отправки, а не вместо
    // проверки: счётчик должен отражать то, что реально ушло в сеть.
    void Record(TimePoint now);

    // Riot ответил 429 с заголовком Retry-After.
    //
    // Отдельный механизм, а не ещё одна запись в окно: сервер сказал
    // «молчи до этого момента», и никакая арифметика по окнам это
    // не отменяет. Пока время не наступило, DelayUntilAllowed обязан
    // возвращать остаток ожидания, даже если все окна пусты.
    void BlockUntil(TimePoint until);

    // Сколько запросов учтено в окне с индексом window_index на момент now.
    // Существует ради тестов и журнала отладки — по нему видно,
    // насколько близко к потолку идёт выгрузка.
    int Used(std::size_t window_index, TimePoint now) const;

private:
    struct Bucket {
        Window window;
        std::deque<TimePoint> hits;  // времена отправок, старые слева
    };

    std::vector<Bucket> buckets_;
    TimePoint blocked_until_{};  // значение по умолчанию = «не заблокировано»
};

}  // namespace sintence

#endif  // SINTENCE_DATA_RATE_LIMITER_H
