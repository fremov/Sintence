#ifndef COURSE_TOPIC00_KDA_H
#define COURSE_TOPIC00_KDA_H

// Это заголовочный файл: он содержит ОБЪЯВЛЕНИЯ.
// Объявление говорит компилятору «такая функция где-то существует,
// вот её имя, параметры и тип результата». Тела здесь нет.
//
// Include guard (COURSE_TOPIC00_KDA_H) защищает от повторного включения
// в одну и ту же единицу трансляции. Без него второй #include привёл бы
// к повторному определению структуры Kda.

namespace course {

// Определение типа — можно и нужно держать в заголовке.
// Тип не порождает символа в объектном файле, поэтому ODR он не нарушает.
struct Kda {
    int kills = 0;
    int deaths = 0;
    int assists = 0;
};

// Объявление функции. Определение — в kda.cpp, то есть в другой единице
// трансляции. Компилятор поверит на слово, а связывать будет линкер.
double ComputeKda(const Kda& kda);

// inline-функция в заголовке — исключение из правила «в заголовке только
// объявления». inline разрешает несколько одинаковых определений в разных
// единицах трансляции; линкер оставит одно.
inline bool IsPerfectGame(const Kda& kda) { return kda.deaths == 0; }

}  // namespace course

#endif  // COURSE_TOPIC00_KDA_H
