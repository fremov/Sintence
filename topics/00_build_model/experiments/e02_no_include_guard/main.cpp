// Эксперимент 2: заголовок включён дважды, защиты от повторного включения нет.
//
// Собрать:
//   cl /nologo /std:c++17 /EHsc main.cpp
//   g++ -std=c++17 main.cpp -o main
//
// Ожидаемая ошибка: C2011 "Kda": повторное определение типа "struct"
//                   / redefinition of 'struct Kda'.
//
// Это ошибка КОМПИЛЯТОРА: препроцессор честно вставил текст kda.h два раза,
// и компилятор увидел два определения одного типа в одной единице трансляции.
//
// В реальном коде ты почти никогда не пишешь два #include подряд — но легко
// получаешь то же самое через цепочку: a.h включает b.h, b.h включает c.h,
// и c.h уже был включён выше.
//
// Почини: добавь include guard в kda.h.

#include "kda.h"
#include "kda.h"

int main() {
    Kda kda{10, 5, 5};
    return kda.kills;
}
