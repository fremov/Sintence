#ifndef COURSE_TOPIC02_MATCH_FILE_H
#define COURSE_TOPIC02_MATCH_FILE_H

#include <cstdio>
#include <string>

// ============================================================================
// Задача 2.1 — MatchFile: RAII на настоящем ресурсе
//
// Критерии приёмки (что значит «готово» сверх зелёных тестов):
//   1. Конструктор захватывает ресурс, деструктор освобождает. Больше нигде
//      в коде нет ни одного вызова fclose.
//   2. Деструктор корректен и тогда, когда файл открыть не удалось.
//      fclose(nullptr) — это неопределённое поведение, а не «ничего страшного».
//   3. Копирование объекта запрещено явно, через = delete, а не «мы просто
//      не будем его копировать».
//   4. Все методы, которые не меняют объект, — const (тема 1 никуда не делась).
//   5. Заглушек и TODO в файле не осталось.
//
// Одна идея этой задачи: владение ресурсом уникально. Один открытый файл —
// один объект, который за него отвечает и закрывает его ровно один раз.
//
// Перемещение здесь сознательно не требуется — оно появится в задаче 2.2.
// Побочный эффект ты увидишь сам: такой MatchFile нельзя ни вернуть из функции
// по значению, ни положить в std::vector. Это не поломка, это цена, и в 2.2
// станет понятно, чем за неё платят.
// ============================================================================

namespace course {

class MatchFile {
public:
    // Открывает файл на чтение в бинарном режиме.
    //
    // Несуществующий путь — это не ошибка и не исключение: файл мог быть удалён
    // между сканированием каталога и открытием, и анализатор должен пережить это,
    // а не упасть посреди выгрузки. Объект в этом случае создаётся, но IsOpen()
    // возвращает false.
    explicit MatchFile(std::string path);

    // ── Твоя часть ──────────────────────────────────────────────────────────
    // TODO: объяви здесь специальные функции-члены, которые нужны этому классу,
    // и реализуй их в match_file.cpp.
    //
    // Два вопроса, на которые отвечает задача:
    //   1. Что произойдёт с FILE*, когда объект перестанет существовать,
    //      если ты ничего не объявишь?
    //   2. Что произойдёт, если такой объект скопировать? Сколько раз тогда
    //      закроется один и тот же файл и что об этом думает ОС?
    // ────────────────────────────────────────────────────────────────────────

    // true, если файл удалось открыть.
    bool IsOpen() const;

    // Путь, с которым объект создавался, — включая случай, когда файл не открылся.
    // Без него сообщение об ошибке пришлось бы собирать на стороне вызывающего.
    const std::string& Path() const;

    // Сырой дескриптор для чтения. nullptr, если файл не открыт.
    // Владение не передаётся: закрывать его снаружи нельзя, этим занимается
    // деструктор. Тема 6 будет читать через него данные.
    std::FILE* Handle() const;

private:
    std::string path_;
    std::FILE* file_ = nullptr;
};

}  // namespace course

#endif  // COURSE_TOPIC02_MATCH_FILE_H
