// ============================================================================
// Задача 2.2 — MatchPayload: правило пяти на сыром буфере
//
// Критерии приёмки (что значит «готово» сверх зелёных тестов):
//   1. Каждому new[] соответствует ровно один delete[]. Санитайзер молчит:
//      ни утечки, ни двойного освобождения, ни чтения освобождённого.
//   2. Копия глубокая: два объекта — два разных буфера. Копия переживает
//      смерть оригинала.
//   3. Копирующее присваивание корректно при a = a. Наивная реализация
//      «освободить своё, скопировать чужое» на самоприсваивании читает
//      уже освобождённую память.
//   4. Перемещение забирает буфер, а источник остаётся пустым и валидным:
//      Data() == nullptr, Size() == 0. Это контракт, а не случайность,
//      и он проверяется тестом.
//   5. Обе move-функции помечены noexcept — иначе std::vector при расширении
//      будет молча копировать вместо перемещения.
//   6. Заглушек и TODO в файле не осталось.
//
// Одна идея этой задачи: если класс владеет сырым ресурсом, пять специальных
// функций-членов перестают быть бесплатными и становятся твоей работой.
//
// В настоящем коде здесь стоял бы std::vector<char> или std::string, и всё
// это писать не пришлось бы. Задача существует затем, чтобы ты один раз
// написал руками то, что они делают за тебя, — и в задаче 2.3 увидел разницу.
// ============================================================================

