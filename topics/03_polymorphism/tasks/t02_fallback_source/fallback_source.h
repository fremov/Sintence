#ifndef COURSE_TOPIC03_FALLBACK_SOURCE_H
#define COURSE_TOPIC03_FALLBACK_SOURCE_H

#include <string>
#include <vector>

#include "match_source.h"  // задача 3.1 — интерфейс и FixtureMatchSource

// ============================================================================
// Задача 3.2 — FallbackMatchSource: реализация, которая сама держит интерфейс
//
// Критерии приёмки — кратко, подробности и «что именно писать» в TODO
// рядом с телами функций в fallback_source.cpp:
//   1. Класс хранит два источника по ссылке/указателю на базу, ни разу
//      не упоминая конкретную реализацию.
//   2. Все переопределения помечены override.
//   3. LoadMatches спрашивает выбранный источник ровно один раз.
//   4. Заглушек и TODO в файле не осталось.
//
// Одна идея этой задачи: реализация интерфейса сама может состоять
// из других реализаций того же интерфейса, ничего о них не зная.
//
// Зачем это анализатору: по project/ARCHITECTURE.md приложение всегда читает
// с диска, а сеть только наполняет кеш. Это ровно тот выбор, который делает
// этот класс: живой источник, если он доступен, иначе локальные данные.
// ============================================================================

namespace course {

// Источник с запасным вариантом: работает через основной, пока тот доступен,
// иначе переключается на резервный.
//
// Оба источника переданы снаружи и живут дольше этого объекта — владения нет,
// поэтому хранить их надо ссылкой или указателем на MatchSource, а не копией
// (интерфейс копировать запрещено, и это тема 2, а не случайность).
class FallbackMatchSource : public MatchSource {
public:
    FallbackMatchSource(const MatchSource& primary, const MatchSource& backup);

    // Источник, который будет использован прямо сейчас:
    //   основной, если он доступен;
    //   иначе резервный, если доступен он;
    //   иначе nullptr — данных сейчас нет ниоткуда.
    //
    // Метод не виртуальный: он не часть интерфейса MatchSource, а деталь
    // именно этой реализации. Возвращает указатель на базу — вызывающий
    // по-прежнему не знает, какая реализация ему досталась.
    const MatchSource* Active() const;
    
    // ── Твоя часть ──────────────────────────────────────────────────────────
    // TODO: объяви здесь три переопределения интерфейса MatchSource
    // и реализуй их в fallback_source.cpp:
    //
    //   Name()         — имя активного источника, либо "none", если активного нет.
    //   IsAvailable()  — доступен ли хоть один из двух.
    //   LoadMatches()  — записи активного источника, либо пустой вектор.
    //
    // Сигнатуры смотри в match_source.h и переписывай точно, вместе с const.
    // Каждое переопределение помечай override — если сигнатура разойдётся хоть
    // на один const, компилятор скажет об этом сразу, а не в рантайме.
    //
    // Все три реализуются через Active() и не содержат ни одного if про тип
    // источника. Если появился if — интерфейс где-то протёк.
    // ────────────────────────────────────────────────────────────────────────
    std::string Name() const override;
    bool IsAvailable() const override;
    std::vector<MatchEntry> LoadMatches() const override;

private:
    const MatchSource* primary_ = nullptr;
    const MatchSource* backup_ = nullptr;
};

}  // namespace course

#endif  // COURSE_TOPIC03_FALLBACK_SOURCE_H
